"""
make_slim.py — build the code-only deploy of the dashboard.

    venv/Scripts/python.exe make_slim.py [OUT_DIR]      (default ../konjure-dashboard)

Copies nba_prop_dashboard.py and every local module it imports (followed recursively,
including imports inside functions), requirements.txt and .streamlit/config.toml, and
writes a DATA_REMOTE file so data_sync.py pulls the logs from this repo at runtime. No log,
data snapshot or git history goes in: that is the point (see data_sync.py).

Files in OUT_DIR that this script did not produce are left alone, except stale modules from
an earlier build, which are removed so a deleted module does not linger in the deploy.
"""
from __future__ import annotations

import ast
import pathlib
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent
ENTRY = "nba_prop_dashboard"
DATA_REMOTE = "rbingham1982-hash/nba-prop-dashboard@main"
EXTRA = ["requirements.txt", ".streamlit/config.toml", ".streamlit/secrets.toml.example"]
GITIGNORE = """__pycache__/
*.py[cod]
.streamlit/secrets.toml
# Synced at runtime by data_sync.py, never committed here
*.json
!.devcontainer/*.json
nba_data/
*.part
*.db
"""
README = """# Konjure Analytics dashboard (deploy)

Code-only build of the Streamlit app. Generated by `make_slim.py` in the main repo; do not
edit here. The data logs are fetched at runtime from the main repo by `data_sync.py`.
Entry point: `nba_prop_dashboard.py`.
"""


def modules() -> list[str]:
    local = {p.stem for p in ROOT.glob("*.py")}
    seen, todo = set(), [ENTRY, "data_sync"]
    while todo:
        m = todo.pop()
        if m in seen or m not in local:
            continue
        seen.add(m)
        tree = ast.parse((ROOT / f"{m}.py").read_text(encoding="utf-8"))
        for n in ast.walk(tree):
            if isinstance(n, ast.Import):
                todo += [a.name.split(".")[0] for a in n.names]
            elif isinstance(n, ast.ImportFrom) and n.module and not n.level:
                todo.append(n.module.split(".")[0])
    return sorted(seen)


def build(out: pathlib.Path) -> list[str]:
    out.mkdir(parents=True, exist_ok=True)
    mods = modules()
    manifest = out / ".slim_manifest"
    old = set(manifest.read_text().split()) if manifest.exists() else set()
    for stale in old - {f"{m}.py" for m in mods}:
        (out / stale).unlink(missing_ok=True)
    for m in mods:
        shutil.copy2(ROOT / f"{m}.py", out / f"{m}.py")
    for rel in EXTRA:
        src = ROOT / rel
        if src.exists():
            (out / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, out / rel)
    (out / "DATA_REMOTE").write_text(DATA_REMOTE + "\n", encoding="utf-8")
    # data_sync's fallback list, for when the GitHub tree API is rate-limited.
    import subprocess
    tracked = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True,
                             check=True).stdout.split()
    import data_sync
    (out / "DATA_FILES").write_text("\n".join(p for p in tracked if data_sync._wanted(p)) + "\n",
                                    encoding="utf-8")
    (out / ".gitignore").write_text(GITIGNORE, encoding="utf-8")
    (out / "README.md").write_text(README, encoding="utf-8")
    manifest.write_text("\n".join(f"{m}.py" for m in mods) + "\n")
    return mods


if __name__ == "__main__":
    dest = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "konjure-dashboard"
    mods = build(dest.resolve())
    print(f"{len(mods)} modules -> {dest.resolve()}")
